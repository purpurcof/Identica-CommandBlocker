package me.purpurcof.identica.addon.commandblocker.testing.environment;

import me.whereareiam.anvil.api.model.process.Distribution;
import me.whereareiam.anvil.api.model.process.MinecraftProxy;
import me.whereareiam.anvil.api.model.process.MinecraftServer;
import me.whereareiam.anvil.api.model.scenario.AnvilScenario;
import me.whereareiam.anvil.api.model.workspace.AssetSource;
import me.whereareiam.anvil.api.model.workspace.WorkspaceAsset;
import me.whereareiam.anvil.api.model.workspace.WorkspaceCache;
import me.whereareiam.anvil.api.model.workspace.WorkspacePlan;
import me.whereareiam.anvil.api.type.CacheIdentity;
import me.whereareiam.anvil.api.type.Platforms;
import me.whereareiam.anvil.api.type.ProcessLifetime;

import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Builds the network the addon runs in: a Velocity proxy with Identica, its Credential provider and the packaged
 * addon, and one {@code lobby} Paper server. Players stay on the lobby while they authenticate, so the tests only
 * observe what the addon does to them.
 */
public final class IdenticaNetwork {
	public static final String PROXY = "proxy";
	public static final String LOBBY = "lobby";

	/** Identica's data directory inside the proxy workspace. */
	public static final String DATA = "plugins/identica";
	/** The addon's data directory inside the proxy workspace. */
	public static final String ADDON_DATA = "plugins/identica-commandblocker";

	private IdenticaNetwork() {
	}

	/**
	 * Builds a network whose addon has no settings of its own, so the plugin writes its defaults.
	 */
	public static AnvilScenario velocity(String name) {
		return velocity(name, Map.of());
	}

	/**
	 * @param name          scenario name; equal networks share one name, different networks do not
	 * @param addonSettings files of the addon's data directory by relative path
	 */
	public static AnvilScenario velocity(String name, Map<String, String> addonSettings) {
		return AnvilScenario.builder()
				.name(name)
				.entrypoint(PROXY)
				.server(lobby())
				.proxy(proxy(addonSettings))
				.build();
	}

	private static MinecraftProxy proxy(Map<String, String> addonSettings) {
		WorkspacePlan.WorkspacePlanBuilder workspace = WorkspacePlan.builder()
				.asset(artifact("identica", Path.of("plugins", "identica.jar")))
				.asset(artifact("credential", Path.of(DATA, "providers", "credential.jar")))
				.asset(artifact("commandblocker", Path.of("plugins", "identica-commandblocker.jar")))
				.cache(libraries("identica-libraries", Path.of(DATA, ".libraries")))
				.cache(libraries("identica-provider-libraries", Path.of(DATA, "providers", ".libraries")));

		identicaConfiguration().forEach((file, content) -> workspace.asset(text("identica-configuration", Path.of(DATA, file), content)));
		addonSettings.forEach((file, content) -> workspace.asset(text("addon-settings", Path.of(ADDON_DATA, file), content)));

		return MinecraftProxy.builder()
				.name(PROXY)
				.platform(Platforms.VELOCITY)
				.distribution(Distribution.remote("4.2.0", "30"))
				.workspace(workspace.build())
				.server(LOBBY)
				.defaultServer(LOBBY)
				.setting("advanced.login-ratelimit", "0")
				// Tests type commands at once; Velocity's rate limit would drop them or hand them to the backend.
				.setting("advanced.command-rate-limit", "0")
				.setting("advanced.forward-commands-if-rate-limited", "false")
				.build();
	}

	/**
	 * Only Credential is enabled and the journey is interactive, so a player enrolls with it by command. Players are
	 * neither routed to a step server nor to a completion server: they stay on the lobby they joined. Every other
	 * file is generated by Identica, as on a new installation.
	 */
	private static Map<String, String> identicaConfiguration() {
		Map<String, String> files = new LinkedHashMap<>();
		files.put("engine.yml", """
				scenarios:
				  authentication:
				    journeyMode: "INTERACTIVE"
				  registration:
				    journeyMode: "INTERACTIVE"
				""");
		files.put("routing.yml", """
				defaults:
				  step:
				    target: ""
				  complete:
				    target: ""
				""");
		// Priorities as Identica's own tests give them. The default entrypoint hosts are left out, so a provider
		// answers on whatever host the player joins through.
		files.put("providers/providers.yml", """
				providers:
				  - id: premium
				    enabled: false
				    priority: 200
				    entrypoints: []
				  - id: credential
				    enabled: true
				    priority: 100
				    entrypoints: []
				""");
		// Debug level, so a failing run explains itself in the proxy console.
		files.put("settings.yml", """
				level: 3
				""");
		return files;
	}

	/**
	 * A backend only has to be there for players to stand on, so it runs for the whole test run and serves one
	 * network after another.
	 */
	private static MinecraftServer lobby() {
		return MinecraftServer.builder()
				.name(LOBBY)
				.platform(Platforms.PAPER)
				.distribution(Distribution.remote("26.1.2", "74"))
				.memoryMegabytes(768)
				.lifetime(ProcessLifetime.ENGINE)
				.build();
	}

	/** Identica downloads its libraries on first start and validates them itself, so a rebuilt plugin keeps them. */
	private static WorkspaceCache libraries(String group, Path path) {
		return WorkspaceCache.builder().group(group).path(path).identity(CacheIdentity.PROCESS).build();
	}

	private static WorkspaceAsset artifact(String name, Path target) {
		return WorkspaceAsset.builder().group(name).source(AssetSource.artifact(name)).target(target).build();
	}

	private static WorkspaceAsset text(String group, Path target, String content) {
		return WorkspaceAsset.builder().group(group).source(AssetSource.text(content)).target(target).build();
	}
}
